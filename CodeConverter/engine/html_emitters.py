def _esc_dq(s: str) -> str:
    """Escape a string for use inside a double-quoted literal in most languages."""
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\r", "\\r").replace("\t", "\\t")


def _esc_sq(s: str) -> str:
    return s.replace("\\", "\\\\").replace("'", "\\'").replace("\n", "\\n")


def _walk_each(children, fn, depth):
    return [fn(c, depth) for c in children]


