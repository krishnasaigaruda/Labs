def _py_str(s: str) -> str:
    if "\n" not in s and '"""' not in s:
        return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'
    return '"""' + s.replace("\\", "\\\\").replace('"""', '\\"\\"\\"') + '"""'


def _py_attrs(attrs):
    if not attrs:
        return "{}"
    parts = []
    for k, v in attrs.items():
        if v is True:
            parts.append(f"{_py_str(k)}: True")
        else:
            parts.append(f"{_py_str(k)}: {_py_str(str(v))}")
    return "{" + ", ".join(parts) + "}"


def _py_node(node, depth):
    pad = "    " * depth
    k = node["k"]
    if k == "doctype": return f"{pad}Doctype({_py_str(node['value'])})"
    if k == "hcomment": return f"{pad}Comment({_py_str(node['value'])})"
    if k == "text":     return f"{pad}Text({_py_str(node['value'])})"
    if k == "el":
        attrs = _py_attrs(node["attrs"])
        if not node["children"]:
            args = [_py_str(node["tag"])]
            if node["attrs"]:
                args.append(attrs)
            return f"{pad}Tag({', '.join(args)})"
        inner = ",\n".join(_py_node(c, depth + 1) for c in node["children"])
        attr_arg = ", " + attrs if node["attrs"] else ", {}"
        return f"{pad}Tag({_py_str(node['tag'])}{attr_arg}, [\n{inner}\n{pad}])"
    return f"{pad}Text({_py_str(str(node))})"


